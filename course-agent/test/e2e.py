import json, sys, urllib.request
from playwright.sync_api import sync_playwright

OUT = sys.argv[1]
errors = []

with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={"width": 1366, "height": 900}, accept_downloads=True)
    pg.on("pageerror", lambda e: errors.append(str(e)))
    pg.on("console", lambda m: m.type == "error" and errors.append(m.text))
    pg.on("dialog", lambda d: d.accept())
    pg.goto("http://localhost:8787/")
    pg.screenshot(path=f"{OUT}/01_gate.png")
    pg.fill("#gCode", "wrong")
    pg.click("#gGo")
    pg.wait_for_selector("#gErr:not([hidden])")
    print("wrong code msg:", pg.inner_text("#gErr"))
    pg.fill("#gCode", "test-code-1234")
    pg.click("#gGo")
    pg.wait_for_selector("#app:not([hidden])")
    print("conn:", pg.inner_text("#cTxt"))
    pg.fill("#pTitle", "테스트제약 신임 팀장 평가면담")
    pg.fill("[data-in='in.client']", "테스트제약")
    pg.fill("[data-in='in.audience']", "신임 팀장")
    pg.fill("[data-in='in.topic']", "면담 때마다 이의가 나온다. 평가 근거를 기록하지 않는다.")
    pg.screenshot(path=f"{OUT}/02_s1_input.png", full_page=True)
    pg.click("#bGen")
    pg.wait_for_selector("#bApprove", timeout=15000)
    pg.screenshot(path=f"{OUT}/03_s1_out.png", full_page=True)
    print("table rendered:", pg.locator("#outBody table").count(), "tags:", pg.locator("#outBody .tag").count(), "nested li:", pg.locator("#outBody li li").count())
    # 수정 요청
    pg.fill("#fbBox", "학습목표를 4개로")
    pg.click("#bRevise")
    pg.wait_for_selector("text=이번 수정에서 바뀐 것", timeout=15000)
    pg.wait_for_selector("#bApprove")
    # 직접 고치기
    pg.click("#bEdit")
    pg.fill("#editBox", pg.input_value("#editBox") + "\n\n설계자 직접 추가 문장")
    pg.click("#bEditSave")
    print("edit kept:", "설계자 직접 추가 문장" in pg.inner_text("#outBody"))
    pg.click("#bApprove")
    pg.wait_for_selector("h2:has-text('고객 확인 요청')")
    pg.click("#bGen"); pg.wait_for_selector("#bApprove", timeout=15000); pg.click("#bApprove")
    pg.wait_for_selector("h2:has-text('유형·무대 제안')")
    pg.click("#bGen"); pg.wait_for_selector("#bApprove", timeout=15000); pg.click("#bApprove")
    pg.wait_for_selector("h2:has-text('커리큘럼표')")
    print("s3b gen disabled before pick:", pg.is_disabled("#bGen"))
    pg.fill("[data-in='ex.pick']", "안 B로, 롤플레이 2라운드")
    pg.fill("[data-in='ex.start']", "13:00")
    print("s3b gen disabled after pick:", pg.is_disabled("#bGen"))
    pg.click("#bGen"); pg.wait_for_selector("#bApprove", timeout=15000)
    pg.screenshot(path=f"{OUT}/04_s3b.png", full_page=True)
    # 앞 단계 고치면 뒤 단계 표시
    pg.click("[data-go='s1']")
    pg.click("#bUnapprove")
    pg.click("#bEdit"); pg.fill("#editBox", pg.input_value("#editBox") + "\n추가"); pg.click("#bEditSave")
    pg.click("[data-go='s2']")
    print("s2 after s1 change locked:", pg.locator("text=앞 단계 승인이 필요합니다").count() > 0)
    pg.click("[data-go='s1']"); pg.click("#bApprove")
    print("s2 stale warn:", pg.locator("text=앞 단계 산출물이 바뀌었습니다").count() > 0)
    print("rail:", pg.inner_text("#rail").replace("\n", " | "))
    with pg.expect_download() as dl:
        pg.click("#bExport")
    d = dl.value; path = f"{OUT}/{d.suggested_filename}"; d.save_as(path)
    md = open(path, encoding="utf-8").read()
    print("export:", d.suggested_filename, len(md), "sections:", md.count("\n# "))
    # 새로고침 뒤 유지
    pg.reload(); pg.wait_for_selector("#app:not([hidden])")
    print("persist title:", pg.input_value("#pTitle"))
    pg.click("#bSettings"); pg.wait_for_selector("#mSettings:not([hidden])")
    print("knowledge len:", len(pg.input_value("#sKnow")))
    pg.screenshot(path=f"{OUT}/05_settings.png")
    pg.click("[data-close]")
    # 모바일
    m = b.new_page(viewport={"width": 390, "height": 844})
    m.goto("http://localhost:8787/")
    m.fill("#gCode", "test-code-1234"); m.click("#gGo"); m.wait_for_selector("#app:not([hidden])")
    m.screenshot(path=f"{OUT}/06_mobile.png", full_page=False)
    sw = m.evaluate("document.documentElement.scrollWidth")
    print("mobile scrollWidth:", sw)
    b.close()

calls = json.load(urllib.request.urlopen("http://localhost:8789/"))
print("upstream calls:", len(calls))
for c in calls[:2] + calls[-1:]:
    print({k: c[k] for k in ("key", "ver", "model", "max", "stream", "cache", "n", "sysLen")})
print("first msg:", calls[0]["first"])
print("revise last:", calls[1]["last"][:160])
print("s3b last:", [c for c in calls if "3-2" in c["first"]][0]["last"][-200:])
print("errors:", errors)
